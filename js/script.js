async function fetchJSON(relPath) {
  try {
    const res = await fetch(relPath, { cache: 'no-store' });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    return await res.json();
  } catch (err) {
    return null; // silently fall back — this is expected when opened via file:// or pre-first-build
  }
}

async function loadSiteContent() {
  const files = [
    'data/site.json', 'data/hero.json', 'data/about.json', 'data/community.json',
    'data/emergency.json', 'data/section-headings.json', 'data/vets.json',
    'data/services.json', 'data/why-us.json', 'data/wellness-plans.json',
    'data/gallery.json', 'data/testimonials.json', 'data/tips.json',
    'data/faq.json', 'data/awards.json'
  ];
  const results = await Promise.all(files.map(fetchJSON));
  const [site, hero, about, community, emergency, sectionHeadings,
         vets, services, whyUs, wellnessPlans, gallery, testimonials, tips, faq, awards] = results;

  const useArr = (val, fallback) => (Array.isArray(val) && val.length) ? val : fallback;

  return {
    site: site || FALLBACK.site,
    hero: hero || FALLBACK.hero,
    about: about || FALLBACK.about,
    community: community || FALLBACK.community,
    emergency: emergency || FALLBACK.emergency,
    sectionHeadings: sectionHeadings || FALLBACK.sectionHeadings,
    vets: useArr(vets, FALLBACK.vets),
    services: useArr(services, FALLBACK.services),
    whyUs: useArr(whyUs, FALLBACK.whyUs),
    wellnessPlans: useArr(wellnessPlans, FALLBACK.wellnessPlans),
    gallery: useArr(gallery, FALLBACK.gallery),
    testimonials: useArr(testimonials, FALLBACK.testimonials),
    tips: useArr(tips, FALLBACK.tips),
    faq: useArr(faq, FALLBACK.faq),
    awards: useArr(awards, FALLBACK.awards)
  };
}

