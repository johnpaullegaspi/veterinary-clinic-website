function setText(id, text) {
  const el = document.getElementById(id);
  if (el && text != null) el.textContent = text;
}

function renderHero(hero) {
  setText('heroEyebrow', hero.eyebrow);
  setText('heroHeadline', hero.headline);
  setText('heroSubheadline', hero.subheadline);
  setText('heroPrimaryCtaLabel', hero.primaryCtaLabel);
  setText('heroEmergencyCtaLabel', hero.emergencyCtaLabel);

  const trustEl = document.getElementById('heroTrust');
  if (trustEl && Array.isArray(hero.trustBadges)) {
    trustEl.innerHTML = hero.trustBadges.map(b =>
      `<div class="trust-item"><i class="fa-solid ${b.icon}"></i> ${b.text}</div>`
    ).join('');
  }

  const imgMain = document.getElementById('heroImgMain');
  if (imgMain && hero.images && hero.images.main) {
    imgMain.src = hero.images.main.src;
    imgMain.alt = hero.images.main.alt;
  }
  const imgSecondary = document.getElementById('heroImgSecondary');
  if (imgSecondary && hero.images && hero.images.secondary) {
    imgSecondary.src = hero.images.secondary.src;
    imgSecondary.alt = hero.images.secondary.alt;
  }

  if (Array.isArray(hero.stats)) {
    if (hero.stats[0]) { setText('heroStat1Value', hero.stats[0].value); setText('heroStat1Label', hero.stats[0].label); }
    if (hero.stats[1]) { setText('heroStat2Value', hero.stats[1].value); setText('heroStat2Label', hero.stats[1].label); }
  }
}

function renderAbout(about) {
  setText('aboutEyebrow', about.eyebrow);
  setText('aboutHeading', about.heading);
  setText('aboutBody', about.body);
  if (about.mission) { setText('missionTitle', about.mission.title); setText('missionText', about.mission.text); }
  if (about.vision) { setText('visionTitle', about.vision.title); setText('visionText', about.vision.text); }
  if (about.values) { setText('valuesTitle', about.values.title); setText('valuesText', about.values.text); }

  const imgs = about.images || {};
  const map = { aboutImgA: imgs.a, aboutImgB: imgs.b, aboutImgC: imgs.c };
  Object.entries(map).forEach(([id, img]) => {
    if (!img) return;
    const el = document.getElementById(id);
    if (el) { el.src = img.src; el.alt = img.alt; }
  });

  const countersEl = document.getElementById('counters');
  if (countersEl && Array.isArray(about.counters)) {
    countersEl.innerHTML = about.counters.map(c => `
      <div class="counter"><span class="counter-num" data-target="${c.target}">0</span><span class="counter-label">${c.label}</span></div>
    `).join('');
  }
}

